//! Initials for the avatar fallback.
//!
//! Here rather than next to the component that draws the avatar because it is
//! pure, and because getting it right is a *script* problem rather than a
//! rendering one: naive "first character of the name" is fine for Latin and
//! wrong for most of the writing systems this app actually serves.
//!
//! Ported from `shared/src/names.ts`, which asked `Intl.Segmenter` where a
//! reader would split and `toLocaleUpperCase` for the capital. Rust's standard
//! library has the second — `str::to_uppercase` is the full Unicode mapping,
//! agreeing with ICU on every code point — but not the first, so the
//! segmentation annex is carried here: UAX #29 extended grapheme cluster
//! boundaries, rules and table both. Every range in that table was read back
//! out of `Intl.Segmenter` itself, code point by code point, so the Worker, the
//! browser and the original agree letter for letter.

/// Up to two letters, one per name part.
///
/// Burmese writes a syllable as a base consonant plus marks that attach above,
/// below and around it — ကျွန် is one thing a reader would call a character but
/// five code points. Slicing by index leaves an orphaned diacritic, which
/// renders as a dotted circle. Cutting on grapheme cluster boundaries cuts
/// where a reader would.
pub fn initials_of(name: &str) -> String {
    let mut out = String::new();
    for word in name.split(is_space).filter(|word| !word.is_empty()).take(2) {
        out.push_str(&first_grapheme(word));
    }
    out
}

/// The first grapheme cluster of `word`, capitalised.
///
/// A capital can be longer than what it capitalises — ß is SS, ﬁ is FI — so
/// this answers a string rather than a character.
fn first_grapheme(word: &str) -> String {
    word[..first_cluster_end(word)].to_uppercase()
}

/// The whitespace that JavaScript's `trim` and `/\s/` agree on: the ASCII
/// controls, every Unicode space separator, the two line separators and the
/// byte-order mark. A name part is a run of anything else.
///
/// Spelled out rather than left to `char::is_whitespace`, which also counts
/// U+0085 NEXT LINE — a character the original splits names on nowhere.
fn is_space(c: char) -> bool {
    matches!(c,
        '\u{0009}'..='\u{000D}' | '\u{0020}' | '\u{00A0}' | '\u{1680}'
        | '\u{2000}'..='\u{200A}' | '\u{2028}' | '\u{2029}' | '\u{202F}'
        | '\u{205F}' | '\u{3000}' | '\u{FEFF}')
}

// ---- grapheme clusters, UAX #29 --------------------------------------------

/// What the characters already read say about the boundary coming up.
///
/// Three of the break rules look further back than the character immediately
/// before the boundary, and this is the whole of what they need.
#[derive(Clone, Copy)]
struct BreakState {
    /// How many regional indicators run up to and including the last character.
    /// A flag is a *pair* of them, so it is the parity that decides.
    ri: u32,
    /// 0 nothing; 1 a pictograph followed by any number of marks; 2 that same
    /// sequence followed by a zero-width joiner.
    pict: u8,
    /// 0 nothing; 1 an Indic consonant and its marks; 2 the same with a linker
    /// somewhere among them.
    conj: u8,
}

/// Where the first grapheme cluster of `word` ends, as a byte offset.
///
/// The rules are UAX #29's GB1–GB13 in the order the annex states them, which
/// is the order they are written in below. Only the first boundary is wanted,
/// so the walk stops at it.
fn first_cluster_end(word: &str) -> usize {
    let mut chars = word.char_indices();
    let Some((_, first)) = chars.next() else {
        return 0;
    };
    let mut prev = properties_of(first);
    let mut state = advance(BreakState { ri: 0, pict: 0, conj: 0 }, prev);
    for (at, c) in chars {
        let next = properties_of(c);
        if breaks_between(state, prev, next) {
            return at;
        }
        state = advance(state, next);
        prev = next;
    }
    word.len()
}

/// Is there a cluster boundary between two characters, given what came before?
/// Both are property words, not code points — see [`properties_of`].
fn breaks_between(state: BreakState, prev: u8, next: u8) -> bool {
    let before = prev & CLASS;
    let after = next & CLASS;

    // GB3: a carriage return and its line feed are one thing.
    if before == CR && after == LF {
        return false;
    }
    // GB4, GB5: a control character is a cluster of its own, on both sides.
    if before == CR || before == LF || before == CONTROL {
        return true;
    }
    if after == CR || after == LF || after == CONTROL {
        return true;
    }
    // GB6, GB7, GB8: a Hangul syllable spelled out in jamo holds together, and
    // a precomposed one still takes a trailing consonant after it.
    if before == HANGUL_L && matches!(after, HANGUL_L | HANGUL_V | HANGUL_LV | HANGUL_LVT) {
        return false;
    }
    if matches!(before, HANGUL_LV | HANGUL_V) && matches!(after, HANGUL_V | HANGUL_T) {
        return false;
    }
    if matches!(before, HANGUL_LVT | HANGUL_T) && after == HANGUL_T {
        return false;
    }
    // GB9, GB9a, GB9b: a mark belongs to the letter it hangs off — the one
    // after it, except in the handful of scripts that write the mark first.
    if after == EXTEND || after == ZWJ {
        return false;
    }
    if after == SPACING_MARK {
        return false;
    }
    if before == PREPEND {
        return false;
    }
    // GB9c: consonant, virama, consonant is one conjunct letter in the Indic
    // scripts, however many marks are strung between them.
    if state.conj == 2 && is_consonant(next) {
        return false;
    }
    // GB11: emoji, joiner, emoji is one picture.
    if state.pict == 2 && is_pictographic(next) {
        return false;
    }
    // GB12, GB13: regional indicators pair off into flags, two at a time.
    if before == REGIONAL && after == REGIONAL && state.ri % 2 == 1 {
        return false;
    }
    // GB999: everything else breaks.
    true
}

/// Fold one more character into the look-back state.
fn advance(state: BreakState, props: u8) -> BreakState {
    let class = props & CLASS;
    let ri = if class == REGIONAL { state.ri + 1 } else { 0 };

    let pict = if is_pictographic(props) {
        1
    } else if state.pict == 1 && class == EXTEND {
        1
    } else if state.pict == 1 && class == ZWJ {
        2
    } else {
        0
    };

    let conj = if is_consonant(props) {
        1
    } else if state.conj != 0 && is_linker(props) {
        2
    } else if state.conj != 0 && is_conjunct_extend(props) {
        state.conj
    } else {
        0
    };

    BreakState { ri, pict, conj }
}

/// Everything the rules need to know about one character, in one byte: the
/// Grapheme_Cluster_Break class in the low four bits, then four independent
/// properties as flags above them. One lookup rather than five.
fn properties_of(c: char) -> u8 {
    let code = c as u32;
    // The 11,172 precomposed Hangul syllables are one contiguous block, laid
    // out as 19 leading consonants x 21 vowels x 28 trailing consonants — the
    // 28th of which is "none". Dividing evenly means no trailing consonant, so
    // there is no table to carry.
    if (0xAC00..=0xD7A3).contains(&code) {
        return if (code - 0xAC00) % 28 == 0 { HANGUL_LV } else { HANGUL_LVT };
    }

    let at = GRAPHEME_ROWS.partition_point(|row| row.1 < code);
    match GRAPHEME_ROWS.get(at) {
        Some(&(low, _, props)) if code >= low => props,
        _ => OTHER,
    }
}

/// Extended_Pictographic: emoji, and the older symbols that behave like them.
fn is_pictographic(props: u8) -> bool {
    props & 16 != 0
}

/// Indic_Conjunct_Break = Consonant: a letter a virama can weld to another.
fn is_consonant(props: u8) -> bool {
    props & 32 != 0
}

/// Indic_Conjunct_Break = Linker: virama and its relatives.
fn is_linker(props: u8) -> bool {
    props & 64 != 0
}

/// Indic_Conjunct_Break = Extend: what GB9c tolerates between a consonant and
/// the linker welding it to the next one. Every combining mark and the
/// zero-width joiner — but not the zero-width *non*-joiner, which is written
/// precisely to stop a conjunct from forming.
fn is_conjunct_extend(props: u8) -> bool {
    props & 128 != 0
}

